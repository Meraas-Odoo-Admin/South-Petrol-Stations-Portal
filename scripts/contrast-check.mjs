// Contrast table for the design tokens (Phase 6, Part B1). Reads the colours
// from apps/web/tailwind.config.js and checks every text pair at 4.5:1 (3:1 for
// large text) and every UI boundary at 3:1 (WCAG 1.4.11). Prints a markdown
// table; exits 1 when a pair fails. Run: node scripts/contrast-check.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(path.join(root, 'apps/web/tailwind.config.js'), 'utf8');

function token(name) {
  // A flat 'name: "#hex"' or a nested { DEFAULT: '#hex' } entry.
  const flat = new RegExp(`['"]?${name.replace('-', '[-]')}['"]?\\s*:\\s*'(#[0-9A-Fa-f]{6})'`).exec(source);
  if (flat) return flat[1];
  const nested = new RegExp(`${name}\\s*:\\s*\\{[^}]*DEFAULT:\\s*'(#[0-9A-Fa-f]{6})'`).exec(source);
  if (nested) return nested[1];
  throw new Error(`token not found: ${name}`);
}
function sub(group, key) {
  const m = new RegExp(`${group}\\s*:\\s*\\{[^}]*['"]?${key}['"]?\\s*:\\s*'(#[0-9A-Fa-f]{6})'`).exec(source);
  if (!m) throw new Error(`token not found: ${group}.${key}`);
  return m[1];
}

const c = {
  primary: sub('primary', 'DEFAULT'),
  'primary-dark': sub('primary', 'dark'),
  'primary-100': sub('primary', '100'),
  accent: sub('accent', 'DEFAULT'),
  'accent-ink': sub('accent', 'ink'),
  'accent-100': sub('accent', '100'),
  danger: sub('danger', 'DEFAULT'),
  'danger-dark': sub('danger', 'dark'),
  'danger-100': sub('danger', '100'),
  ok: sub('ok', 'DEFAULT'),
  'ok-100': sub('ok', '100'),
  paper: token('paper'),
  surface: token('surface'),
  'surface-alt': token('surface-alt'),
  ink: sub('ink', 'DEFAULT'),
  'ink-soft': sub('ink', 'soft'),
  'ink-faint': sub('ink', 'faint'),
  line: token('line'),
  'line-soft': token('line-soft'),
  white: '#FFFFFF',
};

function lin(v) {
  const s = v / 255;
  return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
}
function luminance(hex) {
  const n = parseInt(hex.slice(1), 16);
  return 0.2126 * lin((n >> 16) & 255) + 0.7152 * lin((n >> 8) & 255) + 0.0722 * lin(n & 255);
}
function ratio(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

